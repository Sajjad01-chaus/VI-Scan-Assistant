const {chromium}=require('../frontend/node_modules/playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true});
 try{
  const base=process.env.BASE_URL||'http://127.0.0.1:8001';
  const page=await browser.newPage({viewport:{width:1512,height:950}});const errors=[];let speechRequests=0;
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/api/sessions/*/speech',r=>{speechRequests++;return r.abort();});
  await page.goto(base);
  const config=await (await page.request.get(base+'/api/config')).json();
  if(config.mode!=='fixture')throw Error('This quota-free check requires fixture mode');
  await page.getByRole('textbox',{name:'Assistant request'}).fill('Open Rohan Desai report');
  await page.getByRole('button',{name:'Send request',exact:true}).click();
  await page.getByRole('heading',{name:'Rohan Desai',exact:true}).waitFor();
  await page.getByRole('button',{name:'Draft editor',exact:true}).click();
  const created=page.waitForResponse(r=>r.url().endsWith('/commands'));
  await page.locator('.sample-dictation').first().click();
  const draft=(await (await created).json()).draft;
  if(draft.findings[1].anatomical_site!=='unspecified'||draft.findings[1].polarity!=='negated')throw Error('Negative finding fixture incorrect');
  const area=page.getByRole('region',{name:'Draft saving'});
  const read=async()=>{const r=await page.request.get(base+'/api/drafts/'+draft.id);if(!r.ok())throw Error('Draft read failed');return r.json();};
  await area.getByRole('button',{name:'Save reviewed draft',exact:true}).click();
  await area.getByRole('status').filter({hasText:'Saved as draft'}).waitFor();
  if(!await area.getByRole('button',{name:'Saved as draft',exact:true}).isDisabled())throw Error('Saved button still invites duplicate saving');
  let persisted=await read();if(persisted.status!=='saved_draft'||!persisted.requires_clinician_review)throw Error('Save did not persist');
  const versions=[persisted.version];
  await page.screenshot({path:'verification/draft-save-feedback.png',fullPage:true});
  await page.reload();await page.getByRole('button',{name:'Draft editor',exact:true}).click();
  await area.getByRole('status').filter({hasText:'Saved as draft'}).waitFor();
  await page.getByLabel('Observation',{exact:true}).first().fill('impacted');
  await area.getByRole('button',{name:'Save reviewed draft',exact:true}).click();
  await area.getByRole('status').filter({hasText:'Saved as draft'}).waitFor();
  persisted=await read();if(persisted.findings[0].observation!=='impacted'||persisted.version<=versions[0])throw Error('Edited finding did not save');versions.push(persisted.version);
  await page.getByLabel('Observation',{exact:true}).first().fill('unsupported infection');
  await area.getByRole('button',{name:'Save reviewed draft',exact:true}).click();
  await area.getByRole('alert').filter({hasText:'Could not save: Unsupported clinical claim'}).waitFor();
  persisted=await read();if(persisted.findings[0].observation!=='impacted')throw Error('Invalid edit reached database');
  await page.getByLabel('Observation',{exact:true}).first().fill('horizontally impacted');
  await page.route('**/api/drafts/*/save',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Controlled temporary save failure'})}),{times:1});
  await area.getByRole('button',{name:'Save reviewed draft',exact:true}).click();
  await area.getByRole('alert').filter({hasText:'Controlled temporary save failure'}).waitFor();
  persisted=await read();if(persisted.status==='saved_draft')throw Error('Failed save presented as persisted success');
  await area.getByRole('button',{name:'Save reviewed draft',exact:true}).click();
  await area.getByRole('status').filter({hasText:'Saved as draft'}).waitFor();
  persisted=await read();if(persisted.status!=='saved_draft')throw Error('Save retry did not recover');versions.push(persisted.version);
  if(errors.length||speechRequests)throw Error(JSON.stringify({errors,speechRequests}));
  fs.writeFileSync('verification/draft-save-feedback.json',JSON.stringify({passed:['unspecified fracture site and negation save without extra fields','success visible beside clicked button','saved button disabled until edits','actual API GET confirms saved status/version','saved footer survives reload','edited finding re-enables saving and persists','invalid claim rejected beside button and database unchanged','forced save 503 visible beside button','retry uses fresh version and persists'],versions,speechRequests,pageErrors:errors,mode:'isolated fixture database',limitation:'No model/STT/TTS calls. One forced 503 is intercepted; other draft operations use the real FastAPI/SQLite implementation. The user’s existing matching draft was separately observed as saved_draft v7, not modified by this test.'},null,2));
  console.log('Draft save feedback, persistence, validation and retry passed with no provider calls.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
