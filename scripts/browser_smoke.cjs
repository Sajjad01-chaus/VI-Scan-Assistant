const {chromium}=require('../frontend/node_modules/playwright');
const path=require('path');
const fs=require('fs');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||undefined,headless:true});
 const page=await browser.newPage({viewport:{width:1512,height:1000},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.BASE_URL||'http://127.0.0.1:8000');
 await page.getByRole('button',{name:'Open Priya’s latest OPG report',exact:true}).click();
 await page.locator('.candidate-list button').filter({hasText:'Priya Sharma'}).click();
 await page.getByRole('heading',{name:'Priya Sharma',exact:true}).waitFor();
 await page.getByRole('button',{name:'Summarize this report'}).click();
 await page.getByText('No evidence of a fracture.',{exact:false}).last().waitFor();
 await page.waitForFunction(()=>document.querySelectorAll('.message.assistant').length>=3);
 await page.locator('.citations button').last().click();
 await page.getByRole('region',{name:'Cited source evidence'}).waitFor();
 await page.getByRole('button',{name:'Close source evidence'}).click();
 await page.screenshot({path:path.join(root,'verification','workspace-report.png'),fullPage:true});
 await page.getByRole('button',{name:'Draft editor'}).click();
 await page.getByRole('button',{name:/02 Possible periapical/}).click();
 await page.getByText('Unsaved preview · clinician review required').waitFor();
 await page.getByRole('heading',{name:'Readable draft report'}).waitFor();
 await page.getByRole('button',{name:'View JSON',exact:true}).click();
 const json=page.getByRole('textbox',{name:'Editable findings JSON'});
 const edited=JSON.parse(await json.inputValue());edited[0].observation='radiolucency';
 await json.fill(JSON.stringify(edited,null,2));
 await page.getByRole('button',{name:'Validate & apply JSON',exact:true}).click();
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('input')).some(i=>i.value==='radiolucency'));
 await page.getByRole('button',{name:'Save reviewed draft'}).click();
 await page.getByText('Saved as draft · review still required').waitFor();
 const historyCount=await page.locator('.message').count();
 await page.reload();
 await page.getByRole('heading',{name:'Priya Sharma',exact:true}).waitFor();
 await page.waitForFunction(count=>document.querySelectorAll('.message').length===count,historyCount);
 await page.getByRole('button',{name:'Draft editor'}).click();
 await page.getByText('Saved as draft · review still required').waitFor();
 if(await page.getByLabel('Observation',{exact:true}).inputValue()!=='radiolucency')throw new Error('Validated JSON edit was not restored');
 await page.screenshot({path:path.join(root,'verification','workspace-draft.png'),fullPage:true});
 await page.getByRole('button',{name:'New session',exact:true}).click();
 await page.getByRole('heading',{name:'A report, one request away.'}).waitFor();
 if(await page.locator('.message').count())throw new Error('New session retained old messages');
 if(errors.length)throw new Error(errors.join('\n'));
 fs.writeFileSync(path.join(root,'verification','browser-smoke.json'),JSON.stringify({viewport:'1512x1000',passed:['ambiguous retrieval','patient selection','source report','contextual summary','exact cited evidence panel','uncertain clinical draft','readable draft','validated JSON edit','save draft','chat and draft restoration after reload','new session reset'],pageErrors:errors},null,2));
 console.log('Browser smoke passed with no page errors.');
 await browser.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
